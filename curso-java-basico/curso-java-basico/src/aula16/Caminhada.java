package aula16;

public class Caminhada {
    public static void main(String[] args) {

        System.out.println("Caminhe até chegar a 100");
        System.out.println("Inicio da caminhada");

        for(int count = 0; count <=100; count+=3){
            System.out.println("Caminhando..." + count);
            System.out.println("Caminhando");
        }
        System.out.println("Voce chegou ao seu destino...");
    }
}
