package aula16;

public class UsodoFor {
    public static void main(String[] args) {

        for(int count = 0; count < 100; count +=5){
            System.out.println("Valor do count: " + count);
        }
        for(int count = 50; count >15; count -=10){
            System.out.println("Valor do count: " + count);
        }
    }
}
